"""
训练管理模块 __init__.py

本模块是 YOLOps 训练子系统的包入口（包初始化文件），负责将内部子模块
的核心功能统一向上层暴露，实现训练全生命周期管理。主要功能包括：

    - create_training_run           创建训练运行记录（同步，仅入库和建目录）
    - start_training_background     将训练任务提交到后台线程异步执行（立即返回）
    - collect_artifacts             训练完成后自动收集模型权重、评估指标、图表等制品
    - parse_results_csv             解析 YOLO 训练输出的 results.csv 文件并提取关键指标

该模块依赖 ultralytics（YOLO）框架执行实际训练，依赖 PostgreSQL 数据库进行
状态持久化，依赖本地文件系统管理训练目录和模型注册目录。
"""

# ---------------------------------------------------------------------------
# 从 trainer 子模块导入训练任务生命周期管理接口
# ---------------------------------------------------------------------------
# create_training_run:
#     功能：在数据库中注册一次新的训练运行记录，包含数据集版本、基础模型、超参数等
#           配置信息，并同时创建对应的文件系统工作目录。
#     参数：数据集标识、模型标识、超参数字典等
#     返回：训练运行记录对象（含运行 ID）
#
# start_training_background:
#     功能：将已创建的训练任务提交到后台线程中执行，避免阻塞 API 响应。
#           该函数会立即返回一个任务标识符，调用方可通过该标识符查询训练进度。
#     参数：训练运行 ID
#     返回：后台任务句柄或线程标识
from app.training.trainer import (
    create_training_run,
    start_training_background,
)

# ---------------------------------------------------------------------------
# 从 artifact_collector 子模块导入训练制品收集与结果解析接口
# ---------------------------------------------------------------------------
# collect_artifacts:
#     功能：训练完成后，将模型权重文件（.pt）、评估指标、可视化图表等产出物
#           从训练临时目录复制到模型注册中心进行持久化存储，并将结构化指标写入数据库。
#     参数：训练运行 ID、训练输出目录路径、模型注册目标路径等
#     返回：制品收集结果（成功/失败状态及收集的文件列表）
#
# parse_results_csv:
#     功能：解析 YOLO 训练过程中自动生成的 results.csv 文件，从中提取最佳 epoch
#           及其对应的精度（Precision）、召回率（Recall）、mAP50、mAP50-95 等
#           关键评估指标，并以结构化字典形式返回。
#     参数：results.csv 文件的绝对路径
#     返回：包含最佳 epoch 及各指标值的字典
from app.training.artifact_collector import (
    collect_artifacts,
    parse_results_csv,
)

# ---------------------------------------------------------------------------
# 模块公开 API 白名单
# ---------------------------------------------------------------------------
# 仅将训练子系统对外暴露的四个核心函数列入白名单，通过 from training import *
# 导入时，仅导入以下名称；避免内部私有函数或子模块名称被意外暴露给调用方。
__all__ = [
    "create_training_run",       # 创建训练运行记录
    "start_training_background", # 异步启动后台训练
    "collect_artifacts",         # 收集训练产出制品
    "parse_results_csv",         # 解析训练结果 CSV
]
