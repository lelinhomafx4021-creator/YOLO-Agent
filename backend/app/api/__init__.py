"""
YOLOps-Agent API 子模块包初始化文件

=============================================================
功能说明
=============================================================
该文件将 `api` 目录标识为一个 Python 包（Package），当外部代码执行
`from app.api import ...` 或 `import app.api` 时，Python 会首先加载
本文件中的内容。

=============================================================
包结构概览
=============================================================
`api` 包下存放所有对外暴露的 HTTP API 路由模块，采用按领域分模块的
组织方式，各模块职责如下：

  - train/    —— 训练任务相关接口
                 包括：创建训练任务、查询训练进度、终止训练、获取训练日志、
                 训练超参配置等。

  - model/    —— 模型管理相关接口
                 包括：模型注册、版本管理、模型下载/上传、模型元信息查询、
                 模型转换（如 ONNX 导出）等。

  - dataset/  —— 数据集管理相关接口
                 包括：数据集创建与上传、标签管理、数据预处理、数据集版本
                 控制、数据增强配置等。

  - system/   —— 系统配置及监控相关接口
                 包括：系统运行状态、硬件资源监控（GPU/CPU/内存）、配置项
                 管理、健康检查（health check）等。

=============================================================
分层架构说明
=============================================================
API 层遵循分层设计原则，各层职责清晰分离：

  1. API 路由层（本包）
     - 负责接收 HTTP 请求、解析路径参数与查询参数
     - 调用 Service 层完成业务逻辑
     - 使用 Pydantic 模型进行请求体验证与响应序列化
     - 统一处理异常并返回标准格式的错误响应

  2. Service 业务逻辑层（app.services）
     - 封装核心业务逻辑，与数据访问层交互
     - 不直接依赖 HTTP 请求/响应对象，便于单元测试

  3. Schema 数据模型层（app.schemas）
     - 定义 Pydantic 数据模型，用于请求/响应的校验与文档生成
     - 自动生成 OpenAPI / Swagger 文档

=============================================================
使用示例
=============================================================
  from app.api.train import router as train_router
  app.include_router(train_router, prefix="/api/v1/train", tags=["训练任务"])

  from app.api.model import router as model_router
  app.include_router(model_router, prefix="/api/v1/models", tags=["模型管理"])

=============================================================
注意事项
=============================================================
- 新增 API 路由模块时，需在本文件底部或对应 __init__.py 中
  导出 router 对象，以便在 app 主入口中统一注册。
- 所有路由函数应通过依赖注入（Depends）获取数据库会话等资源，
  避免在路由函数中直接创建资源。
- 遵循 RESTful 风格命名端点，使用名词复数形式。
"""
