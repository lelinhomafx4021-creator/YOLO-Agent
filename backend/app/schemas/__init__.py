"""
=============================================================================
YOLOps-Agent 数据模型包（schemas）—— 初始化入口

【模块用途】
  本文件是 schemas 包的初始化入口，将子模块（common.py）中定义的所有
  Pydantic 数据模型统一导出，供 API 路由层及其他模块直接引用。
  外部调用方应始终通过此包入口导入，而非直接引入 common 子模块。

【设计原则】
  1. 集中导出 —— 所有对外暴露的 Schema 在此处集中列明，形成清晰的公共 API 边界
  2. 职责单一 —— 各模型负责请求参数的校验与响应结构的定义，不包含业务逻辑
  3. 类型安全 —— 利用 Pydantic 的运行时校验能力，在请求入口处拦截非法数据

【使用示例】
  from app.schemas import DatasetCreate, TrainingCreate

【版本历史】
  - v0.1.0 (2025-01) : 初始版本，导出 common.py 中的通用数据模型
=============================================================================
"""

# ---------------------------------------------------------------------------
# 从 common 子模块导入所有公开 Schema
# ---------------------------------------------------------------------------
# common.py 中定义了 YOLOps 系统各 API 端点共享的 Pydantic 数据模型，涵盖
# 数据集管理、标注操作、预标注以及训练任务等通用请求/响应结构。
# 所有模型均继承自 pydantic.BaseModel，利用 Field 约束实现自动校验。
# ---------------------------------------------------------------------------

from app.schemas.common import (
    # ---------- 数据集 ----------
    DatasetCreate,         # 创建数据集请求，包含名称与描述
    DatasetImportRequest,  # 数据集导入请求，指定源文件路径

    # ---------- 标注 ----------
    AnnotationBox,         # 单个目标检测标注框（YOLO 格式归一化坐标）
    AnnotationUpdate,      # 标注更新请求，提交图片的全部标注框与审核状态
    PrelabelRequest,       # 预标注请求，指定模型权重与置信度阈值

    # ---------- 训练 ----------
    TrainingCreate,        # 创建训练任务请求，包含所有训练超参数
)

# ---------------------------------------------------------------------------
# 包公开成员列表
# ---------------------------------------------------------------------------
# __all__ 定义了 from schemas import * 时的导出范围，
# 同时也作为开发者的快速参考，一目了然地看到本包提供的全部公共类型。
# ---------------------------------------------------------------------------
__all__ = [
    # 数据集
    "DatasetCreate",
    "DatasetImportRequest",

    # 标注
    "AnnotationBox",
    "AnnotationUpdate",
    "PrelabelRequest",

    # 训练
    "TrainingCreate",
]
